"""Write llms.txt at the repository root: an entry point for AI agents and LLM tools.

Offline: it reads docs/manual/INDEX.md (chapter map), docs/index/endpoints.json and
docs/index/chunks.jsonl, so build_index.py calls it at the end and the figures never drift.

  python build_llms.py
"""
import collections
import json
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
INDEX_MD = os.path.join(ROOT, "docs", "manual", "INDEX.md")
INDEX_DIR = os.path.join(ROOT, "docs", "index")
OUT = os.path.join(ROOT, "llms.txt")
RAW = "https://raw.githubusercontent.com/Dennis5882/MIDAS-API/main/"
ROW = re.compile(r"^\| \[([0-9][^\]]*\.md)\]\(\./[^)]+\) \| ([^|]+) \| ([^|]+) \|", re.M)


def chapters():
    """[(file, section, description)] from the chapter table of docs/manual/INDEX.md."""
    with open(INDEX_MD, encoding="utf-8") as f:
        text = f.read()
    rows = [(m[1], m[2].strip(), m[3].strip()) for m in ROW.finditer(text)]
    seen, out = set(), []
    for row in rows:  # the design-code tables of INDEX.md link the same files again
        if row[0] not in seen:
            seen.add(row[0])
            out.append(row)
    return out, text


def design_prefixes(endpoints):
    """file -> sorted URI prefixes (DESIGN/RC/KDS-41-20-2022/ ...) of the design and rating chapters."""
    out = collections.defaultdict(set)
    for rec in endpoints:
        parts = rec["endpoint"].split("/")
        if parts[0] not in ("DESIGN", "RATING"):
            continue
        prefix = "/".join(parts[:3]) + "/" if len(parts) > 3 else rec["endpoint"]
        for doc in rec["doc"]:
            out[doc.split("#")[0]].add(prefix)
    return out


def render(rows, index_text, endpoints, chunks):
    totals = re.search(r"공식 글 ([\d,]+)건\(en-us ([\d,]+) \+ ko 전용 ([\d,]+)\)", index_text)
    articles = totals.group(1) if totals else "?"
    documented = sum(1 for e in endpoints if e["documented"])
    sources = collections.Counter(c["source"] for c in chunks)
    prefixes = design_prefixes(endpoints)

    lines = [
        "# MIDAS-API",
        "",
        "> Curated, source-faithful copy of the MIDAS NX Open API (MIDAS Gen NX · Civil NX) JSON manual,",
        "> structured for developers and AI tools. Not official: the official MIDAS API Online Manual is",
        "> the source of truth, and actual API behaviour is not guaranteed by this repository.",
        "",
        f"Coverage: {articles} official articles, {len(rows)} chapter files, {len(endpoints)} endpoints "
        f"indexed ({documented:,} documented), {len(chunks):,} retrieval chunks. "
        "Generated by `scripts/manual_sync/build_llms.py`; do not edit by hand.",
        "",
        "## How to use this repository",
        "",
        "1. **You know the URI** (e.g. `/db/NODE`): look it up in `docs/index/endpoints.json` "
        "(`endpoint` is upper-cased without the leading slash, e.g. `DB/NODE`). Its `doc` field gives "
        "`chapter.md#anchor`; read that section for methods, parameter table, schema and examples.",
        "2. **You know the task, not the URI**: search `docs/index/chunks.jsonl` (one JSON object per line: "
        "`file`, `heading`, `anchor`, `source`, `endpoints`, `articles`, `jp_only`, `text`), "
        "or scan the chapter map below.",
        "3. **Before writing code**, read [AUTHENTICATION.md](" + RAW + "docs/AUTHENTICATION.md): "
        "base URL `https://moa-engineers.midasit.com:443/gen` (Gen NX) or `/civil` (Civil NX), "
        "header `MAPI-Key`.",
        "",
        "## What you can cite",
        "",
        "| `source` of a chunk | Count | Meaning |",
        "| --- | ---: | --- |",
        f"| `om` | {sources['om']:,} | Official manual content organised per endpoint. Parameter descriptions are the official text (some separate tables in chapters 09, 10 and 27 still carry older translations). May include `⚠️` notes. |",
        f"| `om-verbatim` | {sources['om-verbatim']:,} | \"OM 원문 추가 필드\" blocks: official Specifications rows copied verbatim. |",
        f"| `repo-example` | {sources['repo-example']:,} | Python examples written by this repository. **Not official; do not cite as evidence.** |",
        "",
        "Every endpoint record and chunk carries official article ids (`articles`); the article URL is "
        "the citation of record.",
        "",
        "## Conventions in the chapters",
        "",
        "- Each endpoint section: Input URI → Active Methods → parameter table → JSON Schema / Response HEAD → "
        "Request / Response JSON → Python example.",
        "- Parameter tables use `| No. | 설명 | Key | Value 타입 | 기본값 | 필수 |`. Nesting is shown with `└` "
        "(a second level adds two full-width spaces). Descriptions stay in the official language "
        "(English or Korean); notes added by this repository are in Korean.",
        "- `⚠️` marks a typo or contradiction in the official manual, or where this copy deliberately differs, "
        "with the reason.",
        "- `ᴶ⁾` marks items for MIDAS Civil NX JP version only; the list is `docs/manual/jp_only.json`.",
        "- Settings requests wrap records in `\"Assign\"` (keyed by ID strings); actions, result tables and "
        "reports use `\"Argument\"`.",
        "- Result tables share `POST/TABLE` (or a design-code `TABLE`) and are told apart by `TABLE_TYPE`.",
        "",
        "## Chapter map",
        "",
        "| File | Area | Contents | URI prefix (design / rating) |",
        "| --- | --- | --- | --- |",
    ]
    for name, area, desc in rows:
        prefix = " · ".join(f"`{p}`" for p in sorted(prefixes.get(name, ()))) or ""
        lines.append(f"| [{name}]({RAW}docs/manual/{name}) | {area} | {desc} | {prefix} |")
    lines += [
        "",
        "## Other files",
        "",
        f"- [docs/manual/INDEX.md]({RAW}docs/manual/INDEX.md): full table of contents with design-code tables.",
        f"- [AGENTS.md]({RAW}AGENTS.md): rules for agents that edit or maintain this repository (not needed to use it).",
        f"- [docs/index/endpoints.json]({RAW}docs/index/endpoints.json): endpoint → methods, official "
        "articles, documented sections, request keys, `jp_only`, `documented`.",
        f"- [docs/index/chunks.jsonl]({RAW}docs/index/chunks.jsonl): retrieval chunks (≈3,500 characters max).",
        f"- [docs/plugin/INDEX.md]({RAW}docs/plugin/INDEX.md): MIDAS Plug-in tools built on this API "
        "(GUI walkthroughs, separate from the endpoint manual).",
        f"- [examples/]({'https://github.com/Dennis5882/MIDAS-API/tree/main/examples'}): "
        "Python, VBA, JavaScript and curl examples.",
        "",
    ]
    return "\n".join(lines)


def main(index_dir=INDEX_DIR, out=OUT):
    rows, index_text = chapters()
    with open(os.path.join(index_dir, "endpoints.json"), encoding="utf-8") as f:
        endpoints = json.load(f)["endpoints"]
    with open(os.path.join(index_dir, "chunks.jsonl"), encoding="utf-8") as f:
        chunks = [json.loads(line) for line in f if line.strip()]
    text = render(rows, index_text, endpoints, chunks)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"llms.txt: {len(rows)} chapters, {len(endpoints)} endpoints, {len(chunks)} chunks")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
